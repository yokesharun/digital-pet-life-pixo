#!/usr/bin/env python3
"""Generate ESP32 flash PROGMEM gzip arrays from locally authored web assets."""
from pathlib import Path
import gzip
root=Path(__file__).resolve().parent.parent
entries=[('index.html','PIXO_INDEX_HTML'),('app.css','PIXO_APP_CSS'),('app.js','PIXO_APP_JS'),('setup.html','PIXO_SETUP_HTML'),('setup.js','PIXO_SETUP_JS')]
lines=['#pragma once','// Auto-generated by tools/embed_web.py; edit files under web/ instead.','#include <stdint.h>','']
for fname,name in entries:
    raw=(root/'web'/fname).read_bytes()
    compressed=gzip.compress(raw,compresslevel=9,mtime=0)
    lines.append(f'// {fname}: {len(raw)} bytes source -> {len(compressed)} bytes gzip')
    lines.append(f'static const uint8_t {name}[] PROGMEM = {{')
    for i in range(0,len(compressed),16): lines.append('  '+','.join(f'0x{byte:02x}' for byte in compressed[i:i+16])+',')
    lines.append('};\n')
(root/'PixoWebAssets.h').write_text('\n'.join(lines))
print('Generated',root/'PixoWebAssets.h', 'bytes', sum(len(gzip.compress((root/'web'/f).read_bytes(),mtime=0)) for f,_ in entries))
